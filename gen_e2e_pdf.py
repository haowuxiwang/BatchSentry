"""合成 e2e 测试 PDF 生成（产物 e2e_test.pdf 不入 git，可再生）— 埋入可检测问题验证规则+gmp_basis。

埋点设计：
- 页1 封面：批号 B2024001（R7 批号基准）
- 页2 工序1-2（step_no 1,2 正常签名时间）
- 页3 工序4-5（缺 3 → R10 step_gap）
- 页4 工序6：开始14:00 结束10:00（R1-a time_reversal）
- 页5 批号 B2024002（≠B2024001 → R7）+ 参数超限 35 vs 25-30（R3）
- 页6 复核勾选"否"（R8b completeness）
"""
import fitz

doc = fitz.open()

def page(table_lines: list[str], title: str):
    p = doc.new_page(width=595, height=842)  # A4
    y = 60
    p.insert_text((50, y), title, fontsize=14, fontname="china-s")
    y += 30
    for ln in table_lines:
        p.insert_text((50, y), ln, fontsize=11, fontname="china-s")
        y += 22
    return p

page(["产品: 注射用头孢曲松钠 1.0g", "批号: B2024001", "生产日期: 2026-08-01", "规格: 1000 支/批"], "批生产记录 封面")
page([
    "工序编号 | 工序名称 | 开始时间 | 结束时间 | 操作人 | 复核人",
    "1 | 称量 | 2026-08-01 08:00 | 2026-08-01 08:30 | 张三 | 李四",
    "2 | 配液 | 2026-08-01 09:00 | 2026-08-01 10:00 | 张三 | 李四",
], "工序记录（一）")
page([
    "工序编号 | 工序名称 | 开始时间 | 结束时间 | 操作人 | 复核人",
    "4 | 灌装 | 2026-08-01 13:00 | 2026-08-01 14:00 | 王五 | 李四",
    "5 | 冻干 | 2026-08-01 15:00 | 2026-08-01 20:00 | 王五 | 李四",
], "工序记录（二）")
page([
    "工序编号 | 工序名称 | 开始时间 | 结束时间 | 操作人 | 复核人",
    "6 | 轧盖 | 2026-08-02 14:00 | 2026-08-02 10:00 | 赵六 | 李四",
], "工序记录（三）")
page([
    "批号: B2024002",
    "参数检查项目 | 规格范围 | 实测值 | 判定",
    "灌装温度 | 25-30 ℃ | 35 ℃ | 不合格",
    "冻干真空度 | 0.1-0.3 mbar | 0.2 mbar | 合格",
], "参数记录")
page([
    "复核项目 | 结果 | 复核人 | 复核时间",
    "物料平衡复核 | 否 | QA钱七 | 2026-08-03 09:00",
    "批记录完整性复核 | 是 | QA钱七 | 2026-08-03 09:30",
], "QA 复核记录")

doc.save("e2e_test.pdf")
print("e2e_test.pdf:", doc.page_count, "pages")
